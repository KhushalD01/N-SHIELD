export const HOSPITAL_LOCALITY_SUMMARY: Record<string, number> = NAGPUR_HOSPITAL_DIRECTORY.reduce(
  (acc, hosp) => {
    acc[hosp.locality] = (acc[hosp.locality] || 0) + 1;
    return acc;
  },
  {} as Record<string, number>
);

/**
 * Helper to convert hospital directory records into EssentialService format
 * for universal compatibility across existing N-SHIELD components
 */
export function hospitalToEssentialService(hosp: NagpurHospital) {
  return {
    id: hosp.id,
    name: hosp.name,
    category: "hospital" as const,
    lat: hosp.latitude,
    lng: hosp.longitude,
    phone: hosp.phone,
    address: hosp.address,
    landmark: hosp.locality,
    timing: hosp.is24Hours ? "24/7 Emergency Service" : (hosp.timing || "Regular Hours"),
    is24x7: hosp.is24Hours,
    verified: hosp.verificationStatus === "verified",
    notes: hosp.notes || `${hosp.specialties.slice(0, 3).join(", ")} | ${hosp.locality}`,
    specialties: hosp.specialties.join(", "),
    website: hosp.sourceUrl,
    hospitalDetails: hosp,
  };
}

